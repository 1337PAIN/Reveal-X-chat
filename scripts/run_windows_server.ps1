# Run Reveal-X on this Windows PC as the server, behind an HTTPS tunnel.
#
#   powershell -ExecutionPolicy Bypass -File scripts\run_windows_server.ps1
#
# Then, in a second window, start the tunnel (docs/DEPLOYMENT.md):
#   cloudflared tunnel --url http://localhost:5000
#
# Why each setting is here is in docs/DEPLOYMENT.md, "Running it from a
# Windows PC". In short: the two keys must survive restarts, the server listens
# on this machine only so the tunnel is the one way in, and the app believes
# the tunnel's forwarded client address so one visitor's failed logins do not
# lock out everyone.
#
# The keys are generated on the first run into .server-secrets.ps1 in the
# project root, which git ignores. Back that file up somewhere other than this
# PC: without REVEALX_DATA_KEY the app refuses to start once any two-factor
# secret has been sealed with it, and a new REVEAL_X_SECRET_KEY makes every
# stored image share report as tampered.

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$secrets = Join-Path $root '.server-secrets.ps1'

function New-Base64Key([int]$length) {
    $bytes = New-Object byte[] $length
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
    return [Convert]::ToBase64String($bytes)
}

if (-not (Test-Path $secrets)) {
    $stamp = Get-Date -Format s
    $lines = @(
        "# Generated by scripts/run_windows_server.ps1 on $stamp. Git-ignored.",
        "# KEEP A COPY somewhere other than this PC (see the script for why).",
        ('$env:REVEAL_X_SECRET_KEY = ''{0}''' -f (New-Base64Key 48)),
        ('$env:REVEALX_DATA_KEY = ''{0}''' -f (New-Base64Key 32))
    )
    Set-Content -Path $secrets -Value $lines -Encoding UTF8
    Write-Host "Created $secrets" -ForegroundColor Yellow
    Write-Host "Back it up now: the server cannot recover these keys if it is lost." -ForegroundColor Yellow
}
. $secrets

$env:REVEALX_BIND_HOST = '127.0.0.1'            # only the tunnel on this PC can connect
$env:REVEAL_X_COOKIE_SECURE = 'true'            # the tunnel is HTTPS
$env:REVEALX_TRUST_PROXY = 'true'               # believe the tunnel's client address...
$env:REVEALX_CLIENT_IP_HEADER = 'CF-Connecting-IP'  # ...as Cloudflare sets it

# Optional Google sign-in: a git-ignored file of $env:FIREBASE_* lines.
$firebase = Join-Path $root 'firebase.local.ps1'
if (Test-Path $firebase) { . $firebase }

Set-Location $root
python run.py
